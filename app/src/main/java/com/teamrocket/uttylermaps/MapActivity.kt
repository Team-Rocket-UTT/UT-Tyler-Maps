        super.onDestroy()
    }

    /**
     * Handles the result of the runtime permission request.
     *
     * If all requested permissions (location, and optionally Bluetooth on Android 12+)
     * are granted, sets [hasPermissions] to `true` and immediately begins requesting
     * IndoorAtlas location updates.
     *
     * @param requestCode the request code passed to [requestPermissions]
     * @param permissions the requested permissions
     * @param grantResults the grant results for each permission
     */
    override fun onRequestPermissionsResult(
        requestCode: Int,
        permissions: Array<out String>,
        grantResults: IntArray
    ) {
        super.onRequestPermissionsResult(requestCode, permissions, grantResults)
        if(requestCode == 0 && grantResults.all { it == PackageManager.PERMISSION_GRANTED }) {
            hasPermissions = true
            iaLocationManager.requestLocationUpdates(
                IALocationRequest.create(),
                this
            )
        }
    }

    /**
     * Called by IndoorAtlas when a new indoor location fix is available.
     *
     * This method:
     * 1. Stores the latest [IALocation] in [lastLocation].
     * 2. Maps the IndoorAtlas floor level to a Mappedin [Floor] via [FloorManager.findFloorForLevel].
     * 3. Tracks the user's current floor in [blueDotFloorId].
     * 4. Optionally auto-switches the displayed floor if the `auto_floor_switch` preference is enabled.
     * 5. Updates the [BlueDotManager] with the new position.
     * 6. If navigation is active, updates the navigation path via [NavigationManager.updateNavigationPath].
     *
     * If the map is not yet ready or no matching floor is found, the update is skipped.
     *
     * @param location the new [IALocation] from IndoorAtlas
     */
    override fun onLocationChanged(location: IALocation) {

        lastLocation = location

        if (!mapReady) {
            Log.d("BlueDot", "Map not ready yet, skipping location update")
            return
        }

        val mappedFloor = floorManager.findFloorForLevel(location.floorLevel) ?: return
        blueDotFloorId = mappedFloor.id  // track actual user floor
        if (mappedFloor == null) {
            Log.w("BlueDot", "No Mappedin floor found for IA floorLevel=${location.floorLevel}")
            return
        }

        Log.d(
            "BlueDot",
            "IA floorLevel=${location.floorLevel}, mappedFloor=${mappedFloor.name}"
        )
        //if auto floor switch is enabled, switch floors
        val autoSwitch = prefs.getBoolean("auto_floor_switch", true)
        if (autoSwitch && floorManager.currentFloor?.id != mappedFloor.id) {
            floorManager.switchToFloor(mappedFloor)
            runOnUiThread { ui.highlightFloor(mappedFloor) }
        }
        runOnUiThread {
            ui.highlightFloor(mappedFloor)
        }
        syncBlueDotVisibility()

        blueDotManager.updatePosition(
            lat = location.latitude,
            lon = location.longitude,
            accuracy = location.accuracy.toDouble(),
            floor = mappedFloor
        )
        if (navigationManager.isNavigating) {
            navigationManager.updateNavigationPath(
                location.latitude, location.longitude, mappedFloor.id
            )
        }

    }

    /**
     * Synchronizes the blue dot visibility based on the user's actual floor versus
     * the currently displayed floor.
     *
     * If the user is on a different floor than what is currently being viewed, the
     * blue dot is hidden. When the user returns to (or the map switches to) their
     * actual floor, the blue dot is re-enabled and its position is immediately updated.
     */
    fun syncBlueDotVisibility() {
        val userFloor = blueDotFloorId ?: return
        val displayedFloor = floorManager.currentFloor?.id ?: return

        if (userFloor != displayedFloor) {
            mapView.blueDot.disable()
        } else {
            blueDotManager.enable()
            val loc = lastLocation
            val floor = floorManager.allFloors.find { it.id == userFloor }
            if (loc != null && floor != null) {
                blueDotManager.updatePosition(loc.latitude, loc.longitude, loc.accuracy.toDouble(), floor)
            }
        }
    }

