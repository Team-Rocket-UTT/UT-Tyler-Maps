    /**
     * Adds interactive text labels (and icon badges for amenities) to all named spaces on the map.
     *
     * For each [Space] in the provided list:
     * - Spaces with names containing "Restroom", "Elevator", or "Stair" receive a colored icon
     *   badge with a higher collision ranking so they remain visible at lower zoom levels.
     * - All other named spaces receive a default text-only label.
     *
     * Successfully created labels are stored in [labelMap] keyed by space name for later reference.
     *
     * @param spaces the list of [Space] objects to label on the map
     */
    private fun addLabelsToSpaces(spaces: List<Space>) {
        for (space in spaces) {
            if (space.name.isEmpty()) continue

            val isAmenity = space.name.contains("Restroom", true) ||
                    space.name.contains("Elevator", true) ||
                    space.name.contains("Stair", true)

            val icon = when {
                space.name.contains("Restroom", true) -> restroomIcon
                space.name.contains("Elevator", true) -> elevatorIcon
                space.name.contains("Stair", true) -> stairsIcon
                else -> null
            }
            val bgColor = when {
                space.name.contains("Restroom", true) -> "#4e7498"
                space.name.contains("Elevator", true) -> "#15803D"
                space.name.contains("Stair", true) -> "#15803D"
                else -> null
            }

            val options = if (isAmenity && icon != null) {
                AddLabelOptions(
                    labelAppearance = LabelAppearance(icon = icon, color = bgColor, iconVisibleAtZoomLevel = .7),
                    interactive = true,
                    rank = CollisionRankingTier.HIGH
                )
            } else {
                AddLabelOptions(labelAppearance = LabelAppearance(), interactive = true)
            }

            mapView.labels.add(target = space, text = space.name, options = options) { result ->
                result.onSuccess { label -> if (label != null) labelMap[space.name] = label }
            }
        }
    }

    /**
     * Adds icon labels to all map connections (stairs and elevators) at their coordinate positions.
     *
     * Iterates over all [Connection] objects in the map data. Each connection's coordinates
     * receive an icon label: a stairs icon for [Connection.ConnectionType.STAIRS] and an
     * elevator arrow icon for all other connection types. Labels are styled with a green
     * background and medium collision ranking.
     */
    private fun addConnectionLabels() {
        mapView.mapData.getByType<Connection>(MapDataType.CONNECTION) { result ->
            result.onSuccess { connections ->
                for (connection in connections) {
                    val icon = if (connection.type == Connection.ConnectionType.STAIRS) stairsIcon
                    else """<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="white"><path d="M7 2l5 5H2zm10 0l5 5h-10zM7 22l5-5H2zm10 0l5-5h-10z"/></svg>"""

                    connection.coordinates.forEach { coordinate ->
                        mapView.labels.add(
                            target = coordinate, text = "",
                            options = AddLabelOptions(
                                labelAppearance = LabelAppearance(color = "#15803D", icon = icon),
                                rank = CollisionRankingTier.MEDIUM
                            )
                        )
                    }
                }
            }
        }
    }

    /**
     * Loads and displays safety annotation markers on the map.
     *
     * First removes all existing markers, then checks the user's preference for
     * `show_safety_annotations`. If enabled, queries all [com.mappedin.models.Annotation]
     * objects from the map data and places interactive markers at each annotation's coordinate.
     *
     * If an annotation has an icon URL, it is rendered as an `<img>` element; otherwise,
     * a red circle with a warning symbol is displayed as a fallback.
     */
    private fun loadAnnotations() {
        // Remove existing ones first
        mapView.markers.removeAll {  }


        val showAnnotations = prefs.getBoolean("show_safety_annotations", true)
        if (!showAnnotations) return

        mapView.mapData.getByType<com.mappedin.models.Annotation>(MapDataType.ANNOTATION) { result ->
            result.onSuccess { annotations ->
                for (annotation in annotations) {
                    val coord = annotation.coordinate
                    val iconUrl = annotation.icon?.url

                    val iconHtml = if (iconUrl != null) {
                        """<img src="$iconUrl" width="28" height="28" style="display:block;"/>"""
                    } else {
                        """<div style="background:red;color:white;border-radius:50%;
                        width:28px;height:28px;display:flex;align-items:center;
                        justify-content:center;font-size:14px;">⚠</div>"""
                    }

                    mapView.markers.add(
                        target = coord,
                        html = iconHtml,
                        options = com.mappedin.models.AddMarkerOptions(
                            interactive = AddMarkerOptions.Interactive.True,
                            rank = AddMarkerOptions.Rank.Tier(CollisionRankingTier.MEDIUM)
                        )
                    )
                }
            }
        }
    }

    /**
     * Places the blue dot at a hardcoded latitude/longitude for testing purposes.
     *
     * Updates the [BlueDotManager] position and stores a synthetic [IALocation] in
     * [lastLocation] so that navigation and follow-mode features work without a real
     * IndoorAtlas signal.
     *
     * @param lat the latitude to place the blue dot at
     * @param lon the longitude to place the blue dot at
     * @param floor the [Floor] to associate with the fake location; defaults to [FloorManager.currentFloor]
     */
    private fun setFakeLocation(lat: Double, lon: Double, floor: Floor? = null) {
        val targetFloor = floor ?: floorManager.currentFloor ?: return
        blueDotFloorId = targetFloor.id  // track it here too

        blueDotManager.updatePosition(lat, lon, 3.0, targetFloor)
        lastLocation = IALocation.from(android.location.Location("fake").apply {
            latitude = lat
            longitude = lon
            accuracy = 3.0f
        })
    }

    /**
     * Resets the previously highlighted space to its default visual state.
     *
     * If a space was highlighted (e.g., from a search result or tap), its geometry color
     * and opacity are restored to their initial values and the [highlightedLabelSpace]
     * reference is cleared.
     */
    private fun resetHighlightedLabel() {
        highlightedLabelSpace?.let { prev ->
            mapView.updateState(prev, GeometryUpdateState(
                color = "initial",
                opacity = 1.0
            ))
        }
        highlightedLabelSpace = null
    }

    /**
     * Animates the map camera to center on the user's current indoor location.
     *
     * Uses the most recent [IALocation] stored in [lastLocation] to target the camera
     * at zoom level 20 with a top-down pitch. If no location has been received yet,
     * an error is logged and the method returns without action.
     */
    private fun moveToUserLocation() {
        val location = lastLocation

        if (location == null) {
            Log.e("Location", "No location yet")
            return
        }

        mapView.camera.animateTo(
            CameraTarget(
                center = Coordinate(location.latitude, location.longitude),
                zoomLevel = 20.0,
                pitch = 0.0
            ),
            CameraAnimationOptions(
                duration = 1000,
                easing = EasingFunction.EASE_OUT
            )
        )
    }

    /**
     * Navigates the map camera to a specific room by name.
     *
     * Adds the room name to the search history, locates the matching [Space], switches
     * to its floor if necessary, highlights the space geometry in burnt orange (`#BF5700`),
     * and smoothly animates the camera to center on the room.
     *
     * If no space matching [roomName] is found, an error is logged and the method returns.
     *
     * @param roomName the display name of the room to navigate to (case-insensitive match)
     */
    private fun navigateToRoom(roomName: String) {
        ui.searchHistory.addSearch(roomName)
        val space = allSpaces.find {
            it.name.equals(roomName, ignoreCase = true)
        }

        if (space == null) {
            Log.e("Mappedin", "Could not find space: $roomName")
            return
        }

        //switch to correct floor

        if (space.floor != null && floorManager.currentFloor?.id != space.floor) {
            // Find the matching Floor object from your FloorManager
            val targetFloor = floorManager.allFloors.find { it.id == space.floor }
            if (targetFloor != null) {
                floorManager.switchToFloor(targetFloor)
                ui.highlightFloor(targetFloor)
            }
        }

        //clear old highlight before setting new one
        resetHighlightedLabel()
        mapView.updateState(space, GeometryUpdateState(
            color = "#BF5700",
            opacity = 0.6
        ))
        highlightedLabelSpace = space

        //zoom camera to the room
        mapView.camera.animateTo(
            CameraTarget(
                center = space.center,
                zoomLevel = 20.0,
                pitch = 0.0
            ),
            CameraAnimationOptions(
                duration = 1000,
                easing = EasingFunction.EASE_OUT
            )
        )
    }

    /**
     * Removes all labels from the map and re-adds them for every space and connection.
     *
     * This is useful after a theme change or filter reset to ensure labels are rendered
     * with the correct styling and visibility.
     */
    fun reAddAllLabels() {
        mapView.labels.removeAll()
        addLabelsToSpaces(allSpaces)
        addConnectionLabels()
    }

    /**
     * Handles tap events on the map surface.
     *
     * Determines what was tapped from the [com.mappedin.models.ClickPayload]:
     * - If an annotation marker was tapped, displays a toast with the annotation's type and group.
     * - If a filter is active, only shows the info panel for tapped spaces without clearing the filter.
     * - Otherwise, highlights the tapped space and displays its info panel. Tapping empty
     *   space dismisses the info panel and resets any highlight.
     *
     * @param payload the click payload from the Mappedin SDK containing tapped spaces, labels, and markers
     */
    private fun handleMapClick(payload: com.mappedin.models.ClickPayload?) {
        resetRunnable?.let { resetHandler.removeCallbacks(it) }

        val clickedSpace = payload?.spaces?.firstOrNull()
            ?: payload?.labels?.firstOrNull()?.let { label ->
                allSpaces.find { it.name == label.text }
            }

        // if user taps an annotation marker
        payload?.markers?.firstOrNull()?.let { marker ->
            annotationMarkerMap[marker.id]?.let { annotation ->
                runOnUiThread {
                    android.widget.Toast.makeText(this, "${annotation.type} (${annotation.group})", android.widget.Toast.LENGTH_SHORT).show()
                }
                return
            }
        }

        if (ui.isFilterActive()) {
            if (clickedSpace != null && clickedSpace.name.isNotBlank()) {
                runOnUiThread { showInfoPanelForSpace(clickedSpace) }
            }
            return
        }

        resetHighlightedLabel()
        if (clickedSpace == null) {
            runOnUiThread { navigationManager.dismissInfoPanel() }
            return
        }
        if (clickedSpace.name.isNotBlank()) {
            //highlight the room and show info panel
            highlightSpace(clickedSpace)
            runOnUiThread { showInfoPanelForSpace(clickedSpace) }
        }
    }

    /**
     * Applies a burnt-orange highlight to the given space's geometry on the map.
     *
     * Cancels any pending reset runnable, updates the space's color to `#BF5700` at
     * 60% opacity, and stores the space reference in [highlightedLabelSpace] so it
     * can be reset later.
     *
     * @param space the [Space] to visually highlight
     */
    private fun highlightSpace(space: Space) {
        resetRunnable?.let { resetHandler.removeCallbacks(it) }
        mapView.updateState(space, GeometryUpdateState(color = "#BF5700", opacity = 0.6))
        highlightedLabelSpace = space
    }

    /**
     * Displays the info panel for a given space with optional directions functionality.
     *
     * Delegates to [NavigationManager.showSpaceInfoPanel] to render the bottom sheet.
     * If the user has a valid location fix, the "Directions" button will initiate
     * turn-by-turn navigation from the user's current position to the selected space,
     * respecting the user's accessible-routes preference.
     *
     * @param space the [Space] to display information about
     */
    private fun showInfoPanelForSpace(space: Space) {
        navigationManager.showSpaceInfoPanel(
            space = space,
            hasLocation = lastLocation != null,
            onDirections = {
                val loc = lastLocation ?: return@showSpaceInfoPanel
                val floor = blueDotFloorId ?: return@showSpaceInfoPanel
                val accessible = prefs.getBoolean("accessible_routes", false)
                syncBlueDotVisibility()
                navigationManager.navigateTo(space, loc.latitude, loc.longitude, floor, accessible)
                syncBlueDotVisibility()
            }
        )
    }

